"""Build the local main-interface data bundle from the cleaned, read-only database."""
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'MainInterface' / 'venom-data.js'
spec = json.loads((ROOT / 'config/venom_input_spec.json').read_text())
assert all(len(c['source_toxin_ids']) == 1 for c in spec['controls'])
presets = json.loads((ROOT / 'PhysicalRendererTest/presets/species-presets.json').read_text())['presets']
preset_names = {p['source_species_name'].casefold(): p['preset_id'] for p in presets}
uri = (ROOT / 'data/processed/venom_diet_2023/serpentshaper.sqlite').resolve().as_uri() + '?mode=ro'
with sqlite3.connect(uri, uri=True) as conn:
    conn.row_factory = sqlite3.Row
    source = conn.execute('SELECT source_id, sha256, sheet, dataset_doi FROM sources WHERE source_id=?', (spec['source_binding']['source_id'],)).fetchone()
    expected = spec['source_binding']
    if not source or (source['sha256'], source['sheet'], source['dataset_doi']) != (expected['workbook_sha256'], expected['sheet'], expected['dataset_doi']):
        raise ValueError('Input spec and database source binding differ')
    rows = conn.execute("SELECT profile_id, species_name, location, source_row, component_sum_pct FROM profiles WHERE measurement_type='proteomics' AND ingestion_status='ready_with_caveats' ORDER BY species_name, source_row").fetchall()
    profiles = []
    for row in rows:
        components = conn.execute('''SELECT c.toxin_id,c.abundance_pct,c.value_status,d.original_label
            FROM components c JOIN toxin_dictionary d USING(toxin_id)
            WHERE c.profile_id=? ORDER BY d.source_column''', (row['profile_id'],)).fetchall()
        # Preserve null values; no taxonomy reconciliation or family merging takes place.
        profiles.append({**dict(row), 'preset_id': preset_names.get(row['species_name'].casefold()),
            'components': [{'toxin_id': c['toxin_id'], 'label': c['original_label'], 'value': c['abundance_pct'], 'status': c['value_status']} for c in components]})
controls = [{k: c[k] for k in ('id','label','short_label','tier','source_toxin_ids','definition','boundaries')} for c in spec['controls']]
payload = {'schema_version':1, 'source_url':'https://doi.org/' + source['dataset_doi'], 'source_sheet':source['sheet'], 'controls':controls, 'profiles':profiles}
OUT.write_text('// Generated by scripts/build_main_interface_data.py; do not edit.\nwindow.SERPENT_VENOM_DATA = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'Wrote {len(profiles)} eligible proteomic profiles and {len(controls)} controls to {OUT.relative_to(ROOT)}')
