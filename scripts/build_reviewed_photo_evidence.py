"""Export accepted photo evidence as source links, never as model features."""
import json
from pathlib import Path
from evaluate_photo_pattern_pilot import load_examples

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'MainInterface/reviewed-photo-evidence.js'


def build():
    examples = load_examples()
    return {'status': 'observational_references_not_renderer_training',
            'evidence_by_species': {e['species']: {
                'image_id': e['image_id'], 'photo_page': e['photo_page'],
                'attribution': e['attribution'], 'visible_pattern': bool(e['visible_pattern']),
                'evidence': e['evidence'],
            } for e in examples}}


def main():
    data = build()
    OUT.write_text('// Generated by scripts/build_reviewed_photo_evidence.py; no photo data is embedded.\n'
                   'window.SERPENT_REVIEWED_PHOTO_EVIDENCE = ' + json.dumps(data, ensure_ascii=True, separators=(',', ':')) + ';\n')
    print('Exported reference links for', len(data['evidence_by_species']), 'source labels.')


if __name__ == '__main__':
    main()
