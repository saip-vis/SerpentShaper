"""Build a tiny, reference-only renderer cue from selected local body patches.

No training, image export, approval or modification of source records occurs.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SAMPLES = ROOT / 'ML/image_traits/color_samples.json'
OUT = ROOT / 'MainInterface/photo-cues.js'
REPORT = ROOT / 'ML/image_traits/rendering_cues.json'


def build():
    samples = json.loads(SAMPLES.read_text())['samples']
    sources, darks, lights = [], [], []
    for sample in samples:
        manifest = ROOT / sample['manifest']
        row = next(x for x in json.loads(manifest.read_text()) if x['image_id'] == sample['image_id'])
        if row.get('review_status') != 'accepted' or row.get('rendering_training_excluded') or row.get('duplicate_of') or row.get('reference_only_exception'):
            raise ValueError('Source must be accepted and not excluded: ' + sample['image_id'])
        if row.get('provider_species_name') != 'Crotalus atrox':
            raise ValueError('Unexpected source species')
        path = manifest.parent / row['local_path']
        if hashlib.sha256(path.read_bytes()).hexdigest() != row['sha256']:
            raise ValueError('Image hash mismatch')
        with Image.open(path) as original:
            image = original.convert('RGB')
            box = sample['bbox']
            if not (len(box) == 4 and 0 <= box[0] < box[2] <= 1 and 0 <= box[1] < box[3] <= 1):
                raise ValueError('Invalid normalized crop')
            crop = image.crop((round(box[0]*image.width), round(box[1]*image.height),
                               round(box[2]*image.width), round(box[3]*image.height)))
            pixels = np.asarray(crop, dtype=np.float64).reshape(-1, 3)
            luminance = pixels @ np.array([.2126, .7152, .0722])
            low, high = np.quantile(luminance, [.20, .85])
            dark = np.median(pixels[luminance <= low], axis=0)
            light = np.median(pixels[luminance >= high], axis=0)
        darks.append(dark); lights.append(light)
        sources.append({k: row.get(k) for k in ('image_id','observation_id','source_page','photo_page','sha256','photo_license','license_version','attribution','review_status')})
        sources[-1]['manifest'] = sample['manifest']
        sources[-1]['bbox'] = sample['bbox']
        sources[-1]['sample_dark_rgb'] = [round(float(x)) for x in dark]
        sources[-1]['sample_light_rgb'] = [round(float(x)) for x in light]
    if len({s['observation_id'] for s in sources}) < 2:
        raise ValueError('Cue requires at least two observation groups')
    cue = {'species': 'Crotalus atrox', 'pattern': 'diamonds', 'dark_rgb': np.mean(darks, axis=0).round().astype(int).tolist(),
           'light_rgb': np.mean(lights, axis=0).round().astype(int).tolist(), 'sources': sources,
           'limitations': 'Two manually selected body patches; photographed colors depend on lighting and do not represent the species range. Source identity and color accuracy are not expert verified. Reference-only; not an image-trained model.'}
    return {'schema_version':1, 'method':'Median RGB of lowest 20% and highest 15% luminance pixels within each manually selected body patch, then equal-image mean.',
            'sample_definition_sha256':hashlib.sha256(SAMPLES.read_bytes()).hexdigest(), 'cues':[cue]}


def main():
    result = build()
    REPORT.write_text(json.dumps(result, indent=2)+'\n')
    OUT.write_text('// Generated by scripts/build_photo_cues.py; do not edit.\nwindow.SERPENT_PHOTO_CUES = '+json.dumps(result, separators=(',',':'))+';\n')
    print('Built reference-only photo cue:', result['cues'][0]['dark_rgb'], result['cues'][0]['light_rgb'])


if __name__ == '__main__':
    main()
