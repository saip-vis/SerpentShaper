const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const style=require('./style-inference.js');
const renderer=require('../PhysicalRendererTest/species-renderer.js');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(__dirname+'/visual-style-model.js','utf8'),sandbox);
const model=sandbox.window.SERPENT_STYLE_MODEL;
const trainingReport=JSON.parse(fs.readFileSync(__dirname+'/../ML/visual_style_model.json','utf8'));
const example=trainingReport.parity_example;
const exampleValues=Object.fromEntries(model.feature_ids.map((id,i)=>[id,example.features[i]]));
const examplePrediction=style.predict(exampleValues,model);
assert.ok(examplePrediction);
example.prediction.forEach((expected,i)=>assert.ok(Math.abs(examplePrediction[i]-expected)<1e-8,`Python and JavaScript must agree for output ${i}`));
vm.runInNewContext(fs.readFileSync(__dirname+'/../PhysicalRendererTest/presets/species-presets.js','utf8'),sandbox);
const get=id=>sandbox.window.SERPENT_PRESETS.presets.find(p=>p.preset_id===id);
const cobra=get('naja_kaouthia'),mamba=get('dendroaspis_polylepis'),diamondback=get('crotalus_atrox'),massasauga=get('sistrurus_catenatus');
const original=JSON.stringify(diamondback);
const values={'3ftx':40,pla2:10,svmp:5},changed={...values,'3ftx':80};
assert.equal(style.concept({'3ftx':40,pla2:10},model,[{preset:cobra,weight:1}]),null,'three inputs are required');
assert.equal(style.concept(values,model,[]),null,'the system must not silently choose a default snake');
const refs=[{preset:diamondback,weight:.7},{preset:massasauga,weight:.3}];
const a=style.concept(values,model,refs),b=style.concept(changed,model,refs);
assert.ok(a&&b);assert.notDeepEqual(a.prediction,b.prediction);
assert.equal(a.preset.source_species_name,'Hypothetical snake concept');
assert.equal(a.preset.artistic_parameters.body_plan,'viper');
assert.equal(a.preset.artistic_parameters.pattern,'diamonds');
assert.equal(a.preset.artistic_parameters.tail_type,'rattle');
assert.notDeepEqual(a.preset.artistic_parameters.body_stations,diamondback.artistic_parameters.body_stations,'anatomy should blend multiple reference shapes');
assert.ok(Math.abs(a.preset.artistic_parameters.head_geometry.length-(.7*72+.3*70))<1e-9,'head geometry should blend compatible references');
assert.equal(JSON.stringify(diamondback),original,'reference presets must not be mutated');
assert.match(a.options.skinColor,/^#[0-9a-f]{6}$/);assert.match(a.options.ringColor,/^#[0-9a-f]{6}$/);
assert.ok(a.options.scaleDetail>=.85&&a.options.scaleDetail<=1.15);
assert.ok(a.options.thickness>=.952&&a.options.thickness<=1.048);
for(const surface of ['dorsal','ventral']){
  const rendering=renderer.render(a.preset,{...a.options,surface,framing:'full'});
  assert.match(rendering.shape.path,/Z$/,'body contour must remain closed');
  assert.doesNotMatch(rendering.svg,/NaN|Infinity/);
}
assert.notEqual(renderer.render(a.preset,{...a.options,surface:'dorsal'}).svg,renderer.render(b.preset,{...b.options,surface:'dorsal'}).svg);
const influenceA=style.concept(values,model,[{preset:cobra,weight:1}]);
const influenceB=style.concept(values,model,[{preset:mamba,weight:1}]);
assert.notDeepEqual(influenceA.prediction,influenceB.prediction,'reference weights must affect the generated style');
const channel=x=>parseInt(x.artistic_parameters.skin_color.slice(1,3),16);
const partial=style.concept(values,model,[{preset:cobra,weight:.25},{preset:mamba,weight:.75}]);
assert.ok(Math.abs(partial.prediction[0]-(style.predict(values,model)[0]+.25*channel(cobra)+.75*channel(mamba))/2)<1e-8,'displayed weights must feed reference style');
assert.equal(partial.preset.artistic_parameters.body_plan,'terrestrial','compatible dominant anatomy is chosen by total reference influence');
console.log('Style model parity, reference-blended anatomy, closed geometry and SVG changes verified.');
