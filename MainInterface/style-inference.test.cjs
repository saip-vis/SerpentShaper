const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const style=require('./style-inference.js');
const renderer=require('../PhysicalRendererTest/species-renderer.js');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(__dirname+'/visual-style-model.js','utf8'),sandbox);
const model=sandbox.window.SERPENT_STYLE_MODEL;
const trainingReport=JSON.parse(fs.readFileSync(__dirname+'/../ML/visual_style_model.json','utf8'));
const example=trainingReport.parity_example;
const exampleValues=Object.fromEntries(model.feature_ids.map((id,i)=>[id,example.features[i]]));
const examplePrediction=style.predict(exampleValues,model);
assert.ok(examplePrediction);
example.prediction.forEach((expected,i)=>assert.ok(Math.abs(examplePrediction[i]-expected)<1e-8,`Python and JavaScript must agree for output ${i}`));
vm.runInNewContext(fs.readFileSync(__dirname+'/../PhysicalRendererTest/presets/species-presets.js','utf8'),sandbox);
const preset=sandbox.window.SERPENT_PRESETS.presets.find(p=>p.preset_id==='naja_kaouthia');
const original=JSON.stringify(preset);
assert.equal(style.concept(preset,{'3ftx':40,pla2:10},model),null,'insufficient data should show the base reference');
const values={'3ftx':40,pla2:10,svmp:5},changed={...values,'3ftx':80};
const a=style.concept(preset,values,model),b=style.concept(preset,changed,model);
assert.ok(a&&b);assert.notDeepEqual(a.prediction,b.prediction);
assert.match(a.options.skinColor,/^#[0-9a-f]{6}$/);assert.match(a.options.ringColor,/^#[0-9a-f]{6}$/);
assert.ok(a.options.scaleDetail>=.85&&a.options.scaleDetail<=1.15);
assert.ok(a.options.width>=.952&&a.options.width<=1.048,'hood width adjustment must stay small');
assert.ok(a.preset.artistic_parameters.mark_spacing>=preset.artistic_parameters.mark_spacing*.85);
assert.ok(a.preset.artistic_parameters.mark_spacing<=preset.artistic_parameters.mark_spacing*1.15);
assert.equal(JSON.stringify(preset),original,'source preset must not be mutated');
const first=renderer.render(a.preset,{...a.options,surface:'dorsal',framing:'full'}).svg;
const second=renderer.render(b.preset,{...b.options,surface:'dorsal',framing:'full'}).svg;
assert.notEqual(first,second,'different compositions should vary the procedural SVG');
assert.doesNotMatch(first,/NaN|Infinity/);
assert.deepEqual(a.preset.artistic_parameters.front_head_profile,preset.artistic_parameters.front_head_profile,'authored head must remain unchanged');
assert.match(renderer.render(a.preset,{...a.options,surface:'dorsal',framing:'full'}).shape.path,/Z$/,'body contour must remain closed');
const mamba=sandbox.window.SERPENT_PRESETS.presets.find(p=>p.preset_id==='dendroaspis_polylepis');
const mambaConcept=style.concept(mamba,values,model);
assert.ok(mambaConcept.options.thickness>=.952&&mambaConcept.options.thickness<=1.048);
assert.match(renderer.render(mambaConcept.preset,{...mambaConcept.options,surface:'dorsal',framing:'full'}).shape.path,/Z$/);
assert.deepEqual(mambaConcept.preset.artistic_parameters.head_geometry,mamba.artistic_parameters.head_geometry);
console.log('Experimental style inference, bounds, closed geometry and SVG changes verified.');
